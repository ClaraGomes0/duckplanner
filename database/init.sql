CREATE TABLE public.disciplinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area VARCHAR(255) NOT NULL DEFAULT 'Geral',
    difficulty INTEGER NOT NULL CHECK (difficulty BETWEEN 1 AND 5),
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE public.disponibilidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia VARCHAR(20) NOT NULL,
    hora_inicio TIME(0) WITHOUT TIME ZONE NOT NULL,
    hora_fim TIME(0) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_disponibilidade_horas CHECK (hora_fim > hora_inicio)
);

CREATE TABLE public.sessoes_estudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana VARCHAR(20) NOT NULL,
    hora_inicio TIME(0) WITHOUT TIME ZONE NOT NULL,
    hora_fim TIME(0) WITHOUT TIME ZONE NOT NULL,
    concluida BOOLEAN NOT NULL DEFAULT FALSE,
    disciplina_id BIGINT NOT NULL,

    CONSTRAINT fk_sessoes_disciplina
        FOREIGN KEY (disciplina_id)
        REFERENCES public.disciplinas(id)
        ON DELETE CASCADE
);
